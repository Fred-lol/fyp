import csv
import io
from collections import Counter

from database.db import db_session
from services.optimization_service import get_plan


def generate_report(plan_id, generated_by):
    plan = get_plan(plan_id)
    if not plan:
        return False, "Loading plan not found.", None
    if plan.get("validation_result") != "Valid":
        return False, "Only a valid saved loading plan can generate a report.", None
    with db_session() as conn:
        existing = conn.execute("SELECT report_id FROM loading_reports WHERE plan_id=?", (plan_id,)).fetchone()
        if existing:
            return True, "Report already exists for this loading plan.", existing["report_id"]
        cur = conn.execute("INSERT INTO loading_reports(plan_id,generated_by) VALUES(?,?)", (plan_id, generated_by))
        return True, "Loading report generated successfully.", cur.lastrowid


def list_reports(lorry_id=None, plan_id=None):
    sql = """
        SELECT r.report_id,r.plan_id,r.generated_at,p.total_boxes,p.space_utilization,
               p.total_weight,p.remaining_weight_capacity,p.validation_result,
               l.plate_number,u.full_name generated_by_name,cp.point_name collection_point
        FROM loading_reports r
        JOIN loading_plans p ON p.plan_id=r.plan_id
        JOIN lorry_profiles l ON l.lorry_id=p.lorry_id
        JOIN users u ON u.user_id=r.generated_by
        LEFT JOIN collection_points cp ON cp.collection_point_id=p.collection_point_id
        WHERE 1=1
    """
    params = []
    if lorry_id:
        sql += " AND p.lorry_id=?"
        params.append(lorry_id)
    if plan_id:
        sql += " AND r.plan_id=?"
        params.append(plan_id)
    sql += " ORDER BY r.generated_at DESC"
    with db_session() as conn:
        return [dict(r) for r in conn.execute(sql, params).fetchall()]


def get_report(report_id):
    with db_session() as conn:
        row = conn.execute(
            """
            SELECT r.*,u.full_name generated_by_name
            FROM loading_reports r
            JOIN users u ON u.user_id=r.generated_by
            WHERE r.report_id=?
            """,
            (report_id,),
        ).fetchone()
    if not row:
        return None
    report = dict(row)
    report["plan"] = get_plan(report["plan_id"])
    plan = report["plan"]
    report["box_breakdown"] = dict(Counter(p["box_name"] for p in plan["placements"]))
    report["unused_space_percent"] = max(0.0, 100.0 - float(plan["space_utilization"]))
    report["weight_usage_percent"] = (
        float(plan["total_weight"]) / float(plan["max_weight"]) * 100.0 if float(plan["max_weight"]) else 0.0
    )
    report["validation_checks"] = [
        "All boxes are inside the lorry internal boundary.",
        "No saved box placements overlap.",
        "The loaded weight is within the selected lorry capacity.",
        "Saved placements passed AquaLoad stacking/support checks during generation.",
    ] if plan.get("validation_result") == "Valid" else ["The loading plan is not valid."]
    util = float(plan["space_utilization"])
    if util < 40:
        report["operational_insight"] = (
            "Low space utilization. If operationally suitable, Staff can consider combining more Ready for Loading orders "
            "going to the same collection point in a future plan."
        )
    elif util < 70:
        report["operational_insight"] = "Moderate space utilization. The plan uses a reasonable portion of the lorry volume."
    else:
        report["operational_insight"] = "High space utilization. The saved plan uses most of the available lorry volume."
    return report


def report_csv_bytes(report_id):
    report = get_report(report_id)
    if not report:
        return None
    plan = report["plan"]
    out = io.StringIO()
    writer = csv.writer(out)
    writer.writerow(["AquaLoad Loading Report"])
    writer.writerow(["Report", f"#{report_id}"])
    writer.writerow(["Loading Plan", f"#{plan['plan_id']}"])
    writer.writerow(["Lorry", plan["plate_number"]])
    writer.writerow(["Collection Point", plan.get("collection_point") or "Not assigned"])
    writer.writerow(["Generated By", report.get("generated_by_name", "")])
    writer.writerow(["Generated At", report["generated_at"]])
    writer.writerow([])
    writer.writerow(["Loading Summary", "Value"])
    writer.writerow(["Orders Included", len(plan["orders"])])
    writer.writerow(["Total Boxes", plan["total_boxes"]])
    writer.writerow(["Seafood / Loaded Weight (kg)", f"{plan['total_weight']:.2f}"])
    writer.writerow(["Maximum Lorry Weight (kg)", f"{plan['max_weight']:.2f}"])
    writer.writerow(["Remaining Weight Capacity (kg)", f"{plan['remaining_weight_capacity']:.2f}"])
    writer.writerow(["Space Utilization (%)", f"{plan['space_utilization']:.2f}"])
    writer.writerow(["Remaining Space (%)", f"{report['unused_space_percent']:.2f}"])
    writer.writerow(["Validation", plan["validation_result"]])
    writer.writerow([])
    writer.writerow(["Orders"])
    writer.writerow(["Order", "Customer", "Seafood Weight (kg)"])
    for order in plan["orders"]:
        writer.writerow([f"#{order['order_id']}", order["customer_name"], f"{order['seafood_weight_kg']:.2f}"])
    writer.writerow([])
    writer.writerow(["Box Size Breakdown"])
    writer.writerow(["Box Template", "Quantity"])
    for box_name, qty in report["box_breakdown"].items():
        writer.writerow([box_name, qty])
    writer.writerow([])
    writer.writerow(["Loading Sequence"])
    writer.writerow(["Sequence", "Order", "Box", "X", "Y", "Z", "Length", "Width", "Height", "Loaded Weight (kg)"])
    for p in plan["placements"]:
        writer.writerow([
            p["sequence_number"], p["order_id"], p["box_name"], p["x"], p["y"], p["z"],
            p["placed_length"], p["placed_width"], p["placed_height"], p["loaded_weight"],
        ])
    return out.getvalue().encode("utf-8")
